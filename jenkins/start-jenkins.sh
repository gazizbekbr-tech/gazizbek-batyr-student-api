#!/bin/bash
#
# Starts the local Jenkins of Batyr Gazizbek and connects the Docker build agent.
# Usage: ./jenkins/start-jenkins.sh
set -euo pipefail
cd "$(dirname "$0")"

# 1. Secrets live only in jenkins/.env (ignored by Git), generated on the first run
if [ ! -f .env ]; then
    {
        echo "JENKINS_ADMIN_PASSWORD=$(openssl rand -hex 12)"
        echo "VERIFY_DB_PASSWORD=$(openssl rand -hex 12)"
    } > .env
    chmod 600 .env
    echo "Created jenkins/.env with new passwords"
fi
set -a; . ./.env; set +a

# 2. Group id of the Docker socket, so the agent user may run docker commands
DOCKER_GID=$(docker run --rm -v /var/run/docker.sock:/s alpine stat -c %g /s)
export DOCKER_GID

# 3. Controller first
docker compose up -d --build jenkins
echo -n "Waiting for Jenkins"
until curl -sf -o /dev/null http://localhost:8080/login; do echo -n "."; sleep 3; done
echo " ready"

# 4. The agent secret is generated by the controller, read it through the API
JENKINS_AGENT_SECRET=$(curl -sf -u "batyr:$JENKINS_ADMIN_PASSWORD" \
    http://localhost:8080/computer/gazizbek-batyr-docker-agent/jenkins-agent.jnlp \
    | sed -n 's/.*<application-desc><argument>\([a-f0-9]*\)<\/argument>.*/\1/p')
export JENKINS_AGENT_SECRET
docker compose up -d --build agent

echo "Jenkins: http://localhost:8080  (user: batyr, password: see jenkins/.env)"
